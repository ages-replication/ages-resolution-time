import os, sys, warnings
import numpy as np
import pandas as pd
import joblib
from sklearn.model_selection import cross_val_score
from ages_common import (TARGET, DIR_BENCH_RND, DIR_BENCH_CHR, ensure, load_prepared,
                         random_split, chronological_split, cv_random, cv_chronological,
                         baseline_models, metric_row, save_versions)
warnings.filterwarnings('ignore')

SPLIT = sys.argv[1] if len(sys.argv) > 1 and sys.argv[1] in ('random', 'chronological') else 'random'
OUT = ensure(DIR_BENCH_RND if SPLIT == 'random' else DIR_BENCH_CHR)
save_versions(f'{OUT}/environment_versions.txt')

df, FEATURE_COLS = load_prepared()
print(f'Loaded: {len(df)} rows, {len(FEATURE_COLS)} features, split={SPLIT}')
print(f'Long-resolution rate: {df[TARGET].mean()*100:.1f}%')

# Split
if SPLIT == 'random':
    X_train, X_test, y_train, y_test = random_split(df, FEATURE_COLS)
    cv = cv_random()
    period = {}
else:
    X_train, X_test, y_train, y_test, d_sorted, k = chronological_split(df, FEATURE_COLS)
    cv = cv_chronological()
    period = {'train_start': str(d_sorted['Created At'].iloc[0].date()),
              'train_end': str(d_sorted['Created At'].iloc[k-1].date()),
              'test_start': str(d_sorted['Created At'].iloc[k].date()),
              'test_end': str(d_sorted['Created At'].iloc[-1].date())}
    print(period)

print(f'Train: {len(X_train)} | Test: {len(X_test)}')
print(f'Train long-resolution rate: {y_train.mean()*100:.1f}%')
print(f'Test long-resolution rate:  {y_test.mean()*100:.1f}%')
split_info = pd.DataFrame([
    {'Set': 'Train', 'N': len(X_train), 'Long-resolution (%)': round(100*y_train.mean(), 1),
     'Ratio short:long': round((1-y_train.mean())/y_train.mean(), 2),
     'Start': period.get('train_start'), 'End': period.get('train_end')},
    {'Set': 'Test', 'N': len(X_test), 'Long-resolution (%)': round(100*y_test.mean(), 1),
     'Ratio short:long': round((1-y_test.mean())/y_test.mean(), 2),
     'Start': period.get('test_start'), 'End': period.get('test_end')},
])
split_info.to_csv(f'{OUT}/table_split_info.csv', index=False)
print(split_info)

# Baseline benchmark
results_base = {}
rows = []
for name, model in baseline_models().items():
    cv_scores = cross_val_score(model, X_train, y_train, cv=cv, scoring='roc_auc', n_jobs=-1)
    model.fit(X_train, y_train)
    y_proba = model.predict_proba(X_test)[:, 1]
    y_pred = (y_proba >= 0.5).astype(int)
    results_base[name] = {'model': model, 'y_pred': y_pred, 'y_proba': y_proba,
                          'cv_scores': cv_scores}
    r = {'Model': name, 'CV AUC': cv_scores.mean(), 'CV AUC (SD)': cv_scores.std()}
    r.update(metric_row(y_test, y_proba, y_pred))
    rows.append(r)
    print(f'{name:22s} CV AUC={cv_scores.mean():.3f} ± {cv_scores.std():.3f}')

df_base = pd.DataFrame(rows).sort_values('MCC', ascending=False).reset_index(drop=True)
df_base.to_csv(f'{OUT}/table_baseline_full_unrounded.csv', index=False)
print(df_base.round(3).to_string(index=False))

joblib.dump((X_train, X_test, y_train, y_test), f'{OUT}/split.pkl')
joblib.dump(cv, f'{OUT}/cv_scheme.pkl')
joblib.dump(results_base, f'{OUT}/results_base.pkl')
print(f'Saved to {OUT}')
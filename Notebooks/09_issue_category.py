import os, sys, warnings
import numpy as np
import pandas as pd
import joblib
from sklearn.metrics import roc_auc_score, matthews_corrcoef, f1_score
from ages_common import (RANDOM_STATE, TARGET, DIR_BENCH_RND,
                         DIR_PROT_B, DIR_PROT_C, DIR_HORIZON, DIR_CATEGORY, ensure, load_prepared,
                         chronological_split, metric_row, save_versions)
warnings.filterwarnings('ignore')
OUT = ensure(DIR_CATEGORY)
save_versions(f'{OUT}/environment_versions.txt')
CATS = ['Bug', 'Improvement', 'Feature', 'Unknown']

df, FEATURE_COLS = load_prepared()
Xtr, Xte, ytr, yte = joblib.load(f'{DIR_BENCH_RND}/split.pkl')
cat_rnd_tr, cat_rnd_te = df.loc[Xtr.index, 'Category'].values, df.loc[Xte.index, 'Category'].values
_, _, ytr_c, yte_c, d_sorted, k = chronological_split(df, FEATURE_COLS)
cat_chr_tr, cat_chr_te = d_sorted['Category'].iloc[:k].values, d_sorted['Category'].iloc[k:].values
Y = {'A': np.asarray(yte), 'B': np.asarray(yte), 'C': np.asarray(yte_c)}
CT = {'A': cat_rnd_te, 'B': cat_rnd_te, 'C': cat_chr_te}

# 1. category mix
rows = []
for setname, cats, yy in [('All issues', df['Category'].values, df[TARGET].values),
                          ('Random split - train', cat_rnd_tr, np.asarray(ytr)),
                          ('Random split - test', cat_rnd_te, np.asarray(yte)),
                          ('Chronological split - train', cat_chr_tr, np.asarray(ytr_c)),
                          ('Chronological split - test', cat_chr_te, np.asarray(yte_c))]:
    for c in CATS:
        m = cats == c
        rows.append({'Set': setname, 'Category': c, 'N': int(m.sum()), 'Share (%)': 100*m.mean(),
                     'Long-resolution (%)': 100*yy[m].mean() if m.any() else np.nan})
mix = pd.DataFrame(rows)
mix.to_csv(f'{OUT}/table_category_mix.csv', index=False)
print(mix.round(1).to_string(index=False))

# 2-4. per-category performance, 14-day horizon
N_BOOT = 2000
rng = np.random.RandomState(RANDOM_STATE)
PR = {P: joblib.load(f'{d}/final_predictions.pkl') for P, d in
      [('B', DIR_PROT_B), ('C', DIR_PROT_C)]}
boot_idx = {}
for P in 'BC':
    for c in CATS:
        n = int((CT[P] == c).sum())
        boot_idx[(P, c)] = [rng.randint(0, n, n) for _ in range(N_BOOT)]

def boot(yt, pr, pd_, idxs):
    a, m, f = [], [], []
    for i in idxs:
        if len(np.unique(yt[i])) < 2: continue
        a.append(roc_auc_score(yt[i], pr[i])); m.append(matthews_corrcoef(yt[i], pd_[i]))
        f.append(f1_score(yt[i], pd_[i], zero_division=0))
    return np.array(a), np.array(m), np.array(f)

rows, deltas = [], []
store = {}
for P in 'BC':
    for model, pr in PR[P].items():
        for c in CATS + ['All']:
            msk = np.ones(len(Y[P]), bool) if c == 'All' else (CT[P] == c)
            yt, pp, pd_ = Y[P][msk], pr['y_proba'][msk], pr['y_pred'][msk]
            r = {'Protocol': P, 'Model': model, 'Category': c, 'N test': int(msk.sum()),
                 'Long-resolution in test': int(yt.sum())}
            r.update(metric_row(yt, pp, pd_))
            if P in 'BC' and c != 'All':
                a, m, f = boot(yt, pp, pd_, boot_idx[(P, c)])
                store[(P, model, c)] = (a, m, f)
                r.update({'AUC CI low': np.percentile(a, 2.5), 'AUC CI high': np.percentile(a, 97.5),
                          'MCC CI low': np.percentile(m, 2.5), 'MCC CI high': np.percentile(m, 97.5),
                          'F1 CI low': np.percentile(f, 2.5), 'F1 CI high': np.percentile(f, 97.5)})
            rows.append(r)
per_cat = pd.DataFrame(rows)
per_cat.to_csv(f'{OUT}/table_category_performance.csv', index=False)

for model in PR['C']:
    for c in CATS:
        b = per_cat[(per_cat.Protocol == 'B') & (per_cat.Model == model) & (per_cat.Category == c)].iloc[0]
        cc = per_cat[(per_cat.Protocol == 'C') & (per_cat.Model == model) & (per_cat.Category == c)].iloc[0]
        ab, mb, fb = store[('B', model, c)]; ac, mc, fc = store[('C', model, c)]
        L = min(len(ab), len(ac))
        dA, dM = ac[:L] - ab[:L], mc[:L] - mb[:L]
        deltas.append({'Model': model, 'Category': c,
                       'AUC (B)': b['Test AUC'], 'AUC (C)': cc['Test AUC'], 'Delta AUC (C-B)': cc['Test AUC'] - b['Test AUC'],
                       'Delta AUC CI low': np.percentile(dA, 2.5), 'Delta AUC CI high': np.percentile(dA, 97.5),
                       'MCC (B)': b['MCC'], 'MCC (C)': cc['MCC'], 'Delta MCC (C-B)': cc['MCC'] - b['MCC'],
                       'Delta MCC CI low': np.percentile(dM, 2.5), 'Delta MCC CI high': np.percentile(dM, 97.5),
                       'N test (B)': b['N test'], 'N test (C)': cc['N test']})
dd = pd.DataFrame(deltas)
dd.to_csv(f'{OUT}/table_category_deltas_C_minus_B.csv', index=False)
print(dd[dd.Model == 'Random Forest'].round(3).to_string(index=False))

# category-only reference predictor
ref = []
for P, ctr, ytrain, cte, ytest in [('B', cat_rnd_tr, np.asarray(ytr), cat_rnd_te, Y['B']),
                                   ('C', cat_chr_tr, np.asarray(ytr_c), cat_chr_te, Y['C'])]:
    rate = pd.Series(ytrain).groupby(ctr).mean()
    score = pd.Series(cte).map(rate).values
    ref.append({'Protocol': P, 'Category-only AUC': roc_auc_score(ytest, score),
                **{f'Train rate {c}': rate.get(c, np.nan) for c in CATS}})
pd.DataFrame(ref).to_csv(f'{OUT}/table_category_only_reference.csv', index=False)
print(pd.DataFrame(ref).round(3).to_string(index=False))

# 5. per-category across horizons (B and C)
hrows = []
for h in [7, 14, 21, 28]:
    f = f'{DIR_HORIZON}/results_{h}d.pkl'
    if h == 14 or not os.path.exists(f):
        if h != 14: continue
        src = {('B', m): PR['B'][m] for m in PR['B']}; src.update({('C', m): PR['C'][m] for m in PR['C']})
        yB, yC = Y['B'], Y['C']
    else:
        r = joblib.load(f); src = r['preds']; yB, yC = r['y_test_random'], r['y_test_chrono']
    for (P, model), pr in src.items():
        if P not in 'BC': continue
        yt_all, ct = (yB, CT['B']) if P == 'B' else (yC, CT['C'])
        for c in CATS:
            msk = ct == c
            yt = yt_all[msk]
            if len(np.unique(yt)) < 2: continue
            r = {'Horizon': h, 'Protocol': P, 'Model': model, 'Category': c, 'N test': int(msk.sum()),
                 'Long-resolution (%) test': 100*yt.mean()}
            r.update(metric_row(yt, pr['y_proba'][msk], pr['y_pred'][msk]))
            hrows.append(r)
hcat = pd.DataFrame(hrows)
hcat.to_csv(f'{OUT}/table_category_by_horizon.csv', index=False)
if not hcat.empty:
    print(hcat[hcat.Model == 'Random Forest'].pivot_table(index=['Category', 'Horizon'], columns='Protocol',
          values=['Test AUC', 'MCC']).round(3).to_string())


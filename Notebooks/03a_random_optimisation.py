import os, sys, time, warnings
import numpy as np
import pandas as pd
import joblib
from sklearn.model_selection import RandomizedSearchCV
from ages_common import (RANDOM_STATE, N_ITER, DIR_BENCH_RND, DIR_BENCH_CHR, DIR_OPT_RND,
                         DIR_OPT_CHR, ensure, search_spaces, save_versions)
warnings.filterwarnings('ignore')

args = sys.argv[1:] if len(sys.argv) > 1 else ['random']
SPLIT = args[0]
IN = DIR_BENCH_RND if SPLIT == 'random' else DIR_BENCH_CHR
OUT = ensure(DIR_OPT_RND if SPLIT == 'random' else DIR_OPT_CHR)
ensure(f'{OUT}/per_model')
save_versions(f'{OUT}/environment_versions.txt')

X_train, X_test, y_train, y_test = joblib.load(f'{IN}/split.pkl')
cv = joblib.load(f'{IN}/cv_scheme.pkl')
df_base = pd.read_csv(f'{IN}/table_baseline_full_unrounded.csv')
selected = df_base.sort_values('CV AUC', ascending=False)['Model'].head(7).tolist()
print('Selected for optimisation (ordered by baseline CV AUC):', selected)

todo = [m for m in args[1:] if m != 'merge'] or ([] if 'merge' in args else selected)
spaces = search_spaces()

for name in todo:
    f = f'{OUT}/per_model/{name.replace(" ", "_")}.pkl'
    if os.path.exists(f):
        print(f'{name}: already done'); continue
    base_pipe, grid = spaces[name]
    print(f'\nRandomizedSearchCV - {name} ...', flush=True)
    t0 = time.time()
    search = RandomizedSearchCV(base_pipe, param_distributions=grid, n_iter=N_ITER,
                                cv=cv, scoring='roc_auc', random_state=RANDOM_STATE,
                                n_jobs=-1, verbose=1)
    search.fit(X_train, y_train)
    dt = time.time() - t0
    print(f'  Best CV AUC = {search.best_score_:.4f}   ({dt/60:.1f} min)', flush=True)
    i = search.best_index_
    row = {'Model': name, 'Best CV AUC': search.best_score_,
           'Best CV AUC (SD)': search.cv_results_['std_test_score'][i],
           'Search time (min)': dt/60}
    row.update({k.replace('clf__', ''): v for k, v in search.best_params_.items()})
    joblib.dump({'estimator': search.best_estimator_, 'row': row,
                 'cv_results': search.cv_results_}, f)

if 'merge' in args or not args[1:]:
    models, rows = {}, []
    for name in selected:
        d = joblib.load(f'{OUT}/per_model/{name.replace(" ", "_")}.pkl')
        models[name] = d['estimator']; rows.append(d['row'])
    df_params = pd.DataFrame(rows)
    df_params.to_csv(f'{OUT}/table_optimised_hyperparameters.csv', index=False)
    joblib.dump(models, f'{OUT}/optimised_models.pkl')
    print(df_params.to_string(index=False))
    print(f'Saved to {OUT}')
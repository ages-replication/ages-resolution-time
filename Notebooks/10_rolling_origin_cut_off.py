# Rolling-origin: Protocol B vs Protocol C la mai multe date de tăiere (modele baseline)
import numpy as np, pandas as pd
from sklearn.base import clone
from sklearn.model_selection import train_test_split
from sklearn.metrics import roc_auc_score, matthews_corrcoef
from ages_common import (RANDOM_STATE, TARGET, PROJECT, MODEL_ORDER, ensure, load_prepared,
                         baseline_models, cv_random, cv_chronological, select_threshold_oof)

OUT = ensure(f'{PROJECT}/10_rolling_origin')
TRAIN_SHARES = [0.5, 0.6, 0.7, 0.8]      # ponderea de antrenare; test = următoarele 20%
TEST_SHARE = 0.2

df, feature_cols = load_prepared()
d = df.sort_values('Created At').reset_index(drop=True)
n = len(d); n_test = n - int(n * 0.8)

def evaluate(X_tr, y_tr, X_te, y_te, cv):
    res = {}
    for name in MODEL_ORDER:
        model = baseline_models()[name]
        thr = select_threshold_oof(model, X_tr, y_tr, cv, verbose=False)
        proba = clone(model).fit(X_tr, y_tr).predict_proba(X_te)[:, 1]
        res[name] = (roc_auc_score(y_te, proba), matthews_corrcoef(y_te, (proba >= thr).astype(int)))
    return pd.DataFrame(res, index=['AUC', 'MCC']).T

rows = []
for s in TRAIN_SHARES:
    k = int(n * s)
    pool = d.iloc[:k + n_test]                       # issue-urile disponibile la această tăietură
    X, y = pool[feature_cols], pool[TARGET]
    # Protocol C: split cronologic, prag din predicții OOF (TimeSeriesSplit)
    C = evaluate(X.iloc[:k], y.iloc[:k], X.iloc[k:], y.iloc[k:], cv_chronological())
    # Protocol B: split aleator stratificat pe aceleași issue-uri, același număr de teste
    X_tr, X_te, y_tr, y_te = train_test_split(X, y, test_size=n_test, stratify=y,
                                              random_state=RANDOM_STATE)
    B = evaluate(X_tr, y_tr, X_te, y_te, cv_random())
    dA, dM = C['AUC'] - B['AUC'], C['MCC'] - B['MCC']
    rows.append({
        'Training share': f'{int(s * 100)}%',
        'Cut-off date': pool['Created At'].iloc[k - 1].date(),
        'Test period end': pool['Created At'].iloc[-1].date(),
        'Long-resolution, chronological train (%)': round(100 * y.iloc[:k].mean(), 2),
        'Long-resolution, chronological test (%)': round(100 * y.iloc[k:].mean(), 2),
        'Mean dAUC C-B (min to max)': f'{dA.mean():.3f} ({dA.min():.3f} to {dA.max():.3f})',
        'Mean dMCC C-B (min to max)': f'{dM.mean():.3f} ({dM.min():.3f} to {dM.max():.3f})',
        'Models with lower AUC under C': f'{(dA < 0).sum()}/7',
        'Models with lower MCC under C': f'{(dM < 0).sum()}/7',
        'Mean MCC B': round(B['MCC'].mean(), 3),
        'Mean MCC C': round(C['MCC'].mean(), 3),
    })
    print(f'cut-off {int(s * 100)}% done')

table = pd.DataFrame(rows)
table.to_csv(f'{OUT}/table_rolling_origin.csv', index=False)

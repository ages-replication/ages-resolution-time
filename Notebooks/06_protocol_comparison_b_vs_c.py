# Bootstrap CIs for C - B (independent resampling of the two test sets)
def boot_stats(y, proba, pred, idx):
    yt, pr, pd_ = y[idx], proba[idx], pred[idx]
    return (roc_auc_score(yt, pr), matthews_corrcoef(yt, pd_), f1_score(yt, pd_, zero_division=0),
            average_precision_score(yt, pr))

N_BOOT = 2000
rng = np.random.RandomState(RANDOM_STATE)
nB, nC = len(yA), len(yC)
idxB = [rng.randint(0, nB, nB) for _ in range(N_BOOT)]
idxC = [rng.randint(0, nC, nC) for _ in range(N_BOOT)]
ci_rows = []
for m in models:
    pb, pc = PR['B'][m], PR['C'][m]
    sb = np.array([boot_stats(yA, pb['y_proba'], pb['y_pred'], i) for i in idxB])
    sc = np.array([boot_stats(yC, pc['y_proba'], pc['y_pred'], i) for i in idxC])
    d = sc - sb
    for j, k in enumerate(['Test AUC', 'MCC', 'F1 (Long)']):
        ci_rows.append({'Model': m, 'Metric': k,
                        'B': T['B'].loc[m, k], 'B CI low': np.percentile(sb[:, j], 2.5),
                        'B CI high': np.percentile(sb[:, j], 97.5),
                        'C': T['C'].loc[m, k], 'C CI low': np.percentile(sc[:, j], 2.5),
                        'C CI high': np.percentile(sc[:, j], 97.5),
                        'Delta C-B': T['C'].loc[m, k] - T['B'].loc[m, k],
                        'Delta CI low': np.percentile(d[:, j], 2.5),
                        'Delta CI high': np.percentile(d[:, j], 97.5),
                        'P(Delta >= 0)': float((d[:, j] >= 0).mean())})
df_ci = pd.DataFrame(ci_rows)

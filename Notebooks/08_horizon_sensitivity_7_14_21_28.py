# ranking stability across horizons (Kendall of MCC ranks, per protocol, vs 14d)
from scipy.stats import kendalltau
tau = []
for P in 'BC':
    r14 = allr[(allr.Horizon == 14) & (allr.Protocol == P)].set_index('Model')['MCC'].rank(ascending=False)
    for h in [7, 21, 28]:
        sub = allr[(allr.Horizon == h) & (allr.Protocol == P)]
        if sub.empty: continue
        rh = sub.set_index('Model')['MCC'].rank(ascending=False)
        t, p = kendalltau(r14, rh.loc[r14.index])
        tau.append({'Protocol': P, 'Horizon vs 14d': h, 'Kendall tau': t, 'p-value': p})
pd.DataFrame(tau).to_csv(f'{OUT}/table_horizon_rank_stability.csv', index=False)
print(pd.DataFrame(tau).round(3).to_string(index=False))


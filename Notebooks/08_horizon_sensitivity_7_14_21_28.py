import os, sys, warnings
import numpy as np
import pandas as pd
import joblib
from sklearn.base import clone
from sklearn.model_selection import StratifiedKFold
from sklearn.metrics import roc_auc_score, matthews_corrcoef, f1_score
from ages_common import (RANDOM_STATE, TARGET, DIR_BENCH_RND, DIR_OPT_RND, DIR_OPT_CHR,
                         DIR_HORIZON, ensure, load_prepared, chronological_split, cv_chronological,
                         oof_proba, f1_max_threshold, metric_row, save_versions)
warnings.filterwarnings('ignore')
OUT = ensure(DIR_HORIZON)
save_versions(f'{OUT}/environment_versions.txt')
HORIZONS = [int(h) for h in sys.argv[1:]] or [7, 21, 28]

df, FEATURE_COLS = load_prepared()
Xtr14, Xte14, _, _ = joblib.load(f'{DIR_BENCH_RND}/split.pkl')
idx_tr, idx_te = Xtr14.index, Xte14.index
models_rnd = joblib.load(f'{DIR_OPT_RND}/optimised_models.pkl')
models_chr = joblib.load(f'{DIR_OPT_CHR}/optimised_models.pkl')

for h in HORIZONS:
    f_out = f'{OUT}/results_{h}d.pkl'
    if os.path.exists(f_out):
        print(f'{h}d already done'); continue
    col = f'{TARGET}_{h}d'
    print(f'\n===== horizon {h} days =====', flush=True)
    res = {'rows': [], 'preds': {}, 'split': []}
    # ---- random split (A, B)
    X_tr, X_te = df.loc[idx_tr, FEATURE_COLS], df.loc[idx_te, FEATURE_COLS]
    y_tr, y_te = df.loc[idx_tr, col], df.loc[idx_te, col]
    cv_b = StratifiedKFold(n_splits=10, shuffle=True, random_state=RANDOM_STATE)
    res['split'].append({'Horizon': h, 'Split': 'random', 'Train long (%)': 100*y_tr.mean(),
                         'Test long (%)': 100*y_te.mean()})
    for name, proto in models_rnd.items():
        pr_oof = oof_proba(proto, X_tr, y_tr, cv_b)
        thr_B = f1_max_threshold(np.asarray(y_tr), pr_oof)[0]
        m = clone(proto); m.fit(X_tr, y_tr)
        proba = m.predict_proba(X_te)[:, 1]
        thr_A = f1_max_threshold(np.asarray(y_te), proba)[0]
        for P, thr in [('A', thr_A), ('B', thr_B)]:
            pred = (proba >= thr).astype(int)
            r = {'Horizon': h, 'Protocol': P, 'Model': name, 'Threshold': thr}
            r.update(metric_row(y_te, proba, pred)); res['rows'].append(r)
            res['preds'][(P, name)] = {'y_proba': proba, 'y_pred': pred, 'index': np.asarray(idx_te)}
        print(f'  random  {name} done', flush=True)
    # ---- chronological split (C)
    X_tr, X_te, y_tr, y_te, d_sorted, k = chronological_split(df, FEATURE_COLS, target=col)
    cv_c = cv_chronological()
    res['split'].append({'Horizon': h, 'Split': 'chronological', 'Train long (%)': 100*y_tr.mean(),
                         'Test long (%)': 100*y_te.mean()})
    for name, proto in models_chr.items():
        pr_oof = oof_proba(proto, X_tr, y_tr, cv_c)
        ok = ~np.isnan(pr_oof)
        thr_C = f1_max_threshold(np.asarray(y_tr)[ok], pr_oof[ok])[0]
        m = clone(proto); m.fit(X_tr, y_tr)
        proba = m.predict_proba(X_te)[:, 1]
        pred = (proba >= thr_C).astype(int)
        r = {'Horizon': h, 'Protocol': 'C', 'Model': name, 'Threshold': thr_C}
        r.update(metric_row(y_te, proba, pred)); res['rows'].append(r)
        res['preds'][('C', name)] = {'y_proba': proba, 'y_pred': pred,
                                     'number': d_sorted['Number'].iloc[k:].values,
                                     'repository': d_sorted['Repository'].iloc[k:].values}
        print(f'  chrono  {name} done', flush=True)
    res['y_test_random'] = df.loc[idx_te, col].values
    res['y_test_chrono'] = np.asarray(y_te)
    joblib.dump(res, f_out)


import os, sys, warnings
import numpy as np
import pandas as pd
import joblib
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from ages_common import (RANDOM_STATE, CLASS_LABELS, DIR_PREP, DIR_BENCH_RND, DIR_BENCH_CHR,
                         DIR_OPT_RND, DIR_OPT_CHR, DIR_PROT_A, DIR_PROT_B, DIR_PROT_C, ensure,
                         oof_proba, f1_max_threshold, select_threshold_on_test, metric_row,
                         confusion_matrix, save_versions)
warnings.filterwarnings('ignore')

FEATURE_COLS = joblib.load(f'{DIR_PREP}/feature_cols.pkl')
CONFIG = {
    'A': dict(bench=DIR_BENCH_RND, opt=DIR_OPT_RND, out=DIR_PROT_A, thr='test',
              title='Protocol A (random split, threshold on test set)'),
    'B': dict(bench=DIR_BENCH_RND, opt=DIR_OPT_RND, out=DIR_PROT_B, thr='oof',
              title='Protocol B (random split, threshold from OOF predictions)'),
    'C': dict(bench=DIR_BENCH_CHR, opt=DIR_OPT_CHR, out=DIR_PROT_C, thr='oof',
              title='Protocol C (chronological split, threshold from OOF predictions)'),
}
protocols = [p for p in sys.argv[1:] if p in CONFIG] or ['A', 'B', 'C']


def plot_confusion(y_test, pred_base, pred_opt, thr, model_name, title, path):
    fig, axes = plt.subplots(2, 2, figsize=(11, 9))
    fig.suptitle(f'{model_name}: baseline vs optimised - {title}', fontsize=12, fontweight='bold')
    configs = [(pred_base, 'threshold=0.50', 'Baseline'),
               (pred_opt, f'threshold={thr:.2f}', 'Optimised')]
    for r, (pred, thr_lbl, lbl) in enumerate(configs):
        cm = confusion_matrix(y_test, pred)
        cmn = confusion_matrix(y_test, pred, normalize='true')
        for col, (mat, fmt, kind) in enumerate([(cm, 'd', 'counts'), (cmn, '.2f', 'row-normalised')]):
            ax = axes[r, col]
            ax.imshow(mat, cmap='Blues')
            for i in range(2):
                for j in range(2):
                    v = mat[i, j]
                    ax.text(j, i, format(v, fmt), ha='center', va='center',
                            color='white' if v > mat.max()*0.6 else 'black', fontsize=12)
            ax.set_xticks([0, 1]); ax.set_xticklabels(CLASS_LABELS)
            ax.set_yticks([0, 1]); ax.set_yticklabels(CLASS_LABELS)
            ax.set_xlabel('Predicted'); ax.set_ylabel('Actual')
            ax.set_title(f'{lbl} ({thr_lbl}) - {kind}', fontsize=10, fontweight='bold')
    plt.tight_layout()
    plt.savefig(path, dpi=300, bbox_inches='tight')
    plt.close(fig)


for P in protocols:
    cfg = CONFIG[P]
    OUT = ensure(cfg['out'])
    save_versions(f'{OUT}/environment_versions.txt')
    print(f'\n --- Protocol {P}')
    X_train, X_test, y_train, y_test = joblib.load(f'{cfg["bench"]}/split.pkl')
    cv = joblib.load(f'{cfg["bench"]}/cv_scheme.pkl')
    models = joblib.load(f'{cfg["opt"]}/optimised_models.pkl')
    params = pd.read_csv(f'{cfg["opt"]}/table_optimised_hyperparameters.csv').set_index('Model')
    base = joblib.load(f'{cfg["bench"]}/results_base.pkl')

    # ---- threshold selection
    thresholds, oof_store = {}, {}
    for name, model in models.items():
        if cfg['thr'] == 'test':
            thr = select_threshold_on_test(model, X_test, y_test, name)

        else:
            proba = oof_proba(model, X_train, y_train, cv)
            ok = ~np.isnan(proba)
            thr, p, r, f1 = f1_max_threshold(np.asarray(y_train)[ok], proba[ok])
            oof_store[name] = proba
            print(f'{name:22s} threshold={thr:.4f}  (OOF: P={p:.3f} R={r:.3f} F1={f1:.3f}, '
                  f'n_oof={ok.sum()})')

        thresholds[name] = thr
    joblib.dump(thresholds, f'{OUT}/thresholds.pkl')


    # ---- final test evaluation
    rows, preds = [], {}
    for name, model in models.items():
        thr = thresholds[name]
        proba = model.predict_proba(X_test)[:, 1]
        pred = (proba >= thr).astype(int)
        preds[name] = {'y_proba': proba, 'y_pred': pred, 'threshold': thr}
        tn, fp, fn, tp = confusion_matrix(y_test, pred).ravel()
        r = {'Model': name, 'Threshold': thr, 'CV AUC ': params.loc[name, 'Best CV AUC'],
             'CV AUC (SD)': params.loc[name, 'Best CV AUC (SD)']}
        r.update(metric_row(y_test, proba, pred))
        r.update({'TP': tp, 'FP': fp, 'TN': tn, 'FN': fn})
        rows.append(r)
    df_final = pd.DataFrame(rows).sort_values('MCC', ascending=False).reset_index(drop=True)
    df_final.to_csv(f'{OUT}/table_final_test_results_unrounded.csv', index=False)
    joblib.dump(preds, f'{OUT}/final_predictions.pkl')
    print(df_final.round(3).drop(columns=['TP', 'FP', 'TN', 'FN']).to_string(index=False))

    MODEL_FINAL, RUNNER_UP = df_final.loc[0, 'Model'], df_final.loc[1, 'Model']
    joblib.dump(MODEL_FINAL, f'{OUT}/model_final_name.pkl')
    joblib.dump(RUNNER_UP, f'{OUT}/runner_up_name.pkl')
    print(f'Final model: {MODEL_FINAL} | Runner-up: {RUNNER_UP}')

    # ---- confusion matrices, baseline vs optimised (final model)
    pb = base[MODEL_FINAL]['y_pred']
    po = preds[MODEL_FINAL]['y_pred']
    cm_rows = []
    for lbl, pr, t in [('Baseline', pb, 0.5), ('Optimised', po, thresholds[MODEL_FINAL])]:
        tn, fp, fn, tp = confusion_matrix(y_test, pr).ravel()
        cm_rows.append({'Configuration': lbl, 'Threshold': t, 'TP': tp, 'FN': fn, 'TN': tn, 'FP': fp})
    pd.DataFrame(cm_rows).to_csv(f'{OUT}/table_confusion_final_model.csv', index=False)
    plot_confusion(y_test, pb, po, thresholds[MODEL_FINAL], MODEL_FINAL, f'Protocol {P}',
                   f'{OUT}/fig_confusion_matrix.png')

    # ---- feature importance (final model; impurity-based for tree ensembles)
    clf = models[MODEL_FINAL].named_steps['clf']
    if hasattr(clf, 'feature_importances_'):
        imp = pd.Series(clf.feature_importances_, index=FEATURE_COLS)
        xlabel = 'Feature importance (impurity-based)'
    else:
        from sklearn.inspection import permutation_importance
        pi = permutation_importance(models[MODEL_FINAL], X_test, y_test, n_repeats=10,
                                    random_state=RANDOM_STATE, scoring='roc_auc', n_jobs=-1)
        imp = pd.Series(pi.importances_mean, index=FEATURE_COLS)
        xlabel = 'Permutation importance (ROC-AUC drop)'
    imp = imp.rename(index={'Contributors Expertise': 'contributors_expertise'})
    imp = imp.sort_values(ascending=False)
    imp.to_csv(f'{OUT}/table_feature_importance.csv', header=['importance'])
    top10 = imp.head(10).sort_values(ascending=True)
    fig, ax = plt.subplots(figsize=(9, 6))
    bars = ax.barh(top10.index, top10.values, color='#2a78d6')
    for b, v in zip(bars, top10.values):
        ax.text(b.get_width() + top10.max()*0.01, b.get_y()+b.get_height()/2, f'{v:.3f}',
                va='center', fontsize=9)
    ax.set_xlabel(xlabel)
    ax.set_title(f'Top 10 features - {MODEL_FINAL} - Protocol {P}', fontweight='bold', fontsize=12)
    ax.set_xlim(0, 0.27)
    ax.grid(axis='x', alpha=0.3); ax.spines[['top', 'right']].set_visible(False)
    plt.tight_layout()
    plt.savefig(f'{OUT}/fig_feature_importance_top10.png', dpi=300, bbox_inches='tight')
    plt.close(fig)
    print(f'Saved to {OUT}')
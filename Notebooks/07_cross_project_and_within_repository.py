import os, sys, warnings
import numpy as np
import pandas as pd
import joblib
from sklearn.base import clone
from sklearn.model_selection import GroupKFold, train_test_split
from sklearn.metrics import roc_auc_score
from scipy.stats import spearmanr, wilcoxon
from statsmodels.stats.multitest import multipletests
from ages_common import (RANDOM_STATE, TARGET, DIR_CROSS, ensure, load_prepared, baseline_models,
                         f1_max_threshold, metric_row, rank_biserial, save_versions)
warnings.filterwarnings('ignore')
OUT = ensure(DIR_CROSS)
save_versions(f'{OUT}/environment_versions.txt')
PART = sys.argv[1:] or ['a', 'c', 'd']

df, FEATURE_COLS = load_prepared()
X, y, groups = df[FEATURE_COLS], df[TARGET], df['Repository']
BUILDERS = baseline_models()
MIN_ISSUES_LORO, MIN_ISSUES_REPL = 100, 400
print(f'{len(df)} issues, {groups.nunique()} repositories')

# (a) Cross-project, GroupKFold over repositories
if 'a' in PART:
    gkf = GroupKFold(n_splits=5)
    rows, fold_info = [], []
    for fold, (tr, te) in enumerate(gkf.split(X, y, groups=groups), 1):
        repos = sorted(groups.iloc[te].unique())
        fold_info.append({'Fold': fold, 'Held-out repositories': ', '.join(repos),
                          'N test': len(te),
                          'Long-resolution (%) test': 100*y.iloc[te].mean(),
                          'Long-resolution (%) train': 100*y.iloc[tr].mean()})
        inner = GroupKFold(n_splits=4)
        for name, proto in BUILDERS.items():
            Xtr, ytr, gtr = X.iloc[tr], y.iloc[tr], groups.iloc[tr]
            # threshold from inner OOF predictions on training repositories
            proba_oof = np.full(len(ytr), np.nan)
            for itr, iva in inner.split(Xtr, ytr, groups=gtr):
                m = clone(proto); m.fit(Xtr.iloc[itr], ytr.iloc[itr])
                proba_oof[iva] = m.predict_proba(Xtr.iloc[iva])[:, 1]
            thr = f1_max_threshold(np.asarray(ytr), proba_oof)[0]
            m = clone(proto); m.fit(Xtr, ytr)
            proba = m.predict_proba(X.iloc[te])[:, 1]
            for rule, t in [('OOF (inner GroupKFold)', thr)]:
                r = {'Model': name, 'Fold': fold, 'Threshold rule': rule, 'Threshold': t,
                     'N test': len(te)}
                r.update(metric_row(y.iloc[te], proba, (proba >= t).astype(int)))
                rows.append(r)
        print(f'fold {fold} done', flush=True)
    df_cross = pd.DataFrame(rows)
    df_cross.to_csv(f'{OUT}/table_cross_project_folds.csv', index=False)
    pd.DataFrame(fold_info).to_csv(f'{OUT}/table_cross_project_fold_composition.csv', index=False)
    agg = (df_cross.groupby(['Threshold rule', 'Model'])
           [['Test AUC', 'MCC']]
           .agg(['mean', 'std', 'min', 'max']))
    agg.columns = [' '.join(c) for c in agg.columns]
    agg.to_csv(f'{OUT}/table_cross_project_summary.csv')
    print(agg.round(3).to_string())

# (c) Leave-one-repository-out and repository characteristics
if 'c' in PART:
    profile = df.groupby('Repository').agg(
        n_issues=(TARGET, 'size'),
        long_resolution_rate=(TARGET, 'mean'),
        median_resolution_days=('Time_Taken_Days', 'median'),
        n_distinct_assignees=('first_assignee', lambda s: s[s != 'none'].nunique()),
        mean_labels=('n_labels', 'mean'),
        share_with_milestone=('has_milestone', 'mean'),
        span_days=('Created At', lambda s: (s.max() - s.min()).days),
    )
    profile['issues_per_year'] = profile['n_issues'] / (profile['span_days'] / 365)
    profile.to_csv(f'{OUT}/table_repository_profile.csv')

    rf_base = BUILDERS['Random Forest']
    rows = []
    for repo in sorted(df['Repository'].unique()):
        te = (df['Repository'] == repo).values
        if te.sum() < MIN_ISSUES_LORO or y[te].nunique() < 2:
            continue
        # baseline RF, threshold from inner GroupKFold OOF on the other repositories
        Xtr, ytr, gtr = X[~te], y[~te], groups[~te]
        pr = np.full(len(ytr), np.nan)
        for itr, iva in GroupKFold(n_splits=5).split(Xtr, ytr, groups=gtr):
            mm = clone(rf_base); mm.fit(Xtr.iloc[itr], ytr.iloc[itr])
            pr[iva] = mm.predict_proba(Xtr.iloc[iva])[:, 1]
        thr = f1_max_threshold(np.asarray(ytr), pr)[0]
        mm = clone(rf_base); mm.fit(Xtr, ytr)
        p_new = mm.predict_proba(X[te])[:, 1]
        r = {'Repository': repo, 'N': int(te.sum()),
            'Long-resolution rate': y[te].mean(),
            'Threshold': thr}
        r.update(metric_row(y[te], p_new, (p_new >= thr).astype(int)))
        rows.append(r)
        print(f'LORO {repo} done', flush=True)
    loro = pd.DataFrame(rows).sort_values('MCC', ascending=False)
    loro.to_csv(f'{OUT}/table_leave_one_repository_out.csv', index=False)

    merged = loro.merge(profile, left_on='Repository', right_index=True)
    factors = ['n_issues', 'long_resolution_rate', 'median_resolution_days', 'n_distinct_assignees',
               'mean_labels', 'share_with_milestone', 'issues_per_year']
    corr = []
    for f in factors:
        rho, p = spearmanr(merged['MCC'], merged[f])
        corr.append({'Factor': f, 'rho': rho, 'p-value': p, 'N repositories': len(merged)})
    dc = pd.DataFrame(corr)
    dc['p (Holm)'] = multipletests(dc['p-value'], method='holm')[1]
    dc.to_csv(f'{OUT}/table_contextual_correlations.csv', index=False)
    print(dc.round(4).to_string(index=False))

# (d) Within-repository replication: random vs chronological split
if 'd' in PART:
    rows = []
    for name, proto in BUILDERS.items():
        for repo in sorted(df['Repository'].unique()):
            sub = df[df['Repository'] == repo].sort_values('Created At').reset_index(drop=True)
            if len(sub) < MIN_ISSUES_REPL:
                continue
            Xr, yr = sub[FEATURE_COLS], sub[TARGET]
            k = int(len(sub) * 0.8)
            m1 = clone(proto); m1.fit(Xr[:k], yr[:k])
            if yr[k:].nunique() < 2:
                continue
            auc_chr = roc_auc_score(yr[k:], m1.predict_proba(Xr[k:])[:, 1])
            Xtr, Xte, ytr, yte = train_test_split(Xr, yr, test_size=(len(sub) - k) / len(sub),
                                                  stratify=yr, random_state=RANDOM_STATE)
            m2 = clone(proto); m2.fit(Xtr, ytr)
            if yte.nunique() < 2:
                continue
            auc_rnd = roc_auc_score(yte, m2.predict_proba(Xte)[:, 1])
            rows.append({'Model': name, 'Repository': repo, 'N': len(sub),
                         'Long-resolution rate (chronological test)': yr[k:].mean(),
                         'Long-resolution rate (random test)': yte.mean(),
                         'AUC random': auc_rnd, 'AUC chronological': auc_chr,
                         'Delta (chronological - random)': auc_chr - auc_rnd})
        print(f'within-repo {name} done', flush=True)
    rep = pd.DataFrame(rows)
    rep.to_csv(f'{OUT}/table_within_repo_replication.csv', index=False)
    w = []
    for name in BUILDERS:
        s = rep[rep['Model'] == name]
        stat, p = wilcoxon(s['AUC chronological'], s['AUC random'])
        w.append({'Model': name, 'N repositories': len(s),
                  'Repositories with negative delta': int((s['Delta (chronological - random)'] < 0).sum()),
                  'Median delta': s['Delta (chronological - random)'].median(),
                  'Mean delta': s['Delta (chronological - random)'].mean(),
                  'W': stat, 'p-value': p,
                  'Rank-biserial r': rank_biserial(s['AUC chronological'], s['AUC random'])})
    dw = pd.DataFrame(w)
    rej, ph, _, _ = multipletests(dw['p-value'], alpha=0.05, method='holm')
    dw['p (Holm)'] = ph; dw['Significant (Holm)'] = rej
    dw.to_csv(f'{OUT}/table_within_repo_wilcoxon.csv', index=False)
    print(dw.round(4).to_string(index=False))
print(f'Saved to {OUT}')
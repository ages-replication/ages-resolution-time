# Statistical testing (Wilcoxon signed-rank on per-fold MCC, Holm correction)

import os, sys, warnings
import numpy as np
import pandas as pd
import joblib
from scipy.stats import wilcoxon
from statsmodels.stats.multitest import multipletests
from sklearn.base import clone
from sklearn.metrics import matthews_corrcoef
from ages_common import (DIR_BENCH_RND, DIR_BENCH_CHR, DIR_OPT_RND, DIR_OPT_CHR, DIR_PROT_A,
                         DIR_PROT_B, DIR_PROT_C, DIR_STATS, ensure, rank_biserial, save_versions)
warnings.filterwarnings('ignore')
OUT = ensure(DIR_STATS)
save_versions(f'{OUT}/environment_versions.txt')

CONFIG = {'A': (DIR_BENCH_RND, DIR_OPT_RND, DIR_PROT_A),
          'B': (DIR_BENCH_RND, DIR_OPT_RND, DIR_PROT_B),
          'C': (DIR_BENCH_CHR, DIR_OPT_CHR, DIR_PROT_C)}

_cache = {}
def mcc_per_fold(key, model, X, y, cv, threshold):
    if key in _cache:
        return _cache[key]
    out = []
    for tr, va in cv.split(X, y):
        m = clone(model)
        m.fit(X.iloc[tr], y.iloc[tr])
        proba = m.predict_proba(X.iloc[va])[:, 1]
        out.append(matthews_corrcoef(y.iloc[va], (proba >= threshold).astype(int)))
    _cache[key] = np.array(out)
    return _cache[key]


main_rows, fold_rows = [], []
for P, (bench, opt, prot) in CONFIG.items():
    X_train, X_test, y_train, y_test = joblib.load(f'{bench}/split.pkl')
    cv = joblib.load(f'{bench}/cv_scheme.pkl')
    base = joblib.load(f'{bench}/results_base.pkl')
    models = joblib.load(f'{opt}/optimised_models.pkl')
    thr = joblib.load(f'{prot}/thresholds.pkl')
    final = joblib.load(f'{prot}/model_final_name.pkl')
    runner = joblib.load(f'{prot}/runner_up_name.pkl')

    print(f'Protocol {P}: final={final}, runner-up={runner}')

    m_final = mcc_per_fold((P, final, 'opt'), models[final], X_train, y_train, cv, thr[final])
    m_run = mcc_per_fold((P, runner, 'opt'), models[runner], X_train, y_train, cv, thr[runner])
    m_base = mcc_per_fold((P, final, 'base'), base[final]['model'], X_train, y_train, cv, 0.5)
    for lab, arr in [(f'{final} (optimised)', m_final), (f'{runner} (optimised)', m_run),
                     (f'{final} (baseline)', m_base)]:
        for i, v in enumerate(arr, 1):
            fold_rows.append({'Protocol': P, 'Configuration': lab, 'Fold': i, 'MCC': v})

    for comp, a, b in [(f'{final} (opt.) vs {runner} (opt.)', m_final, m_run),
                       (f'{final} (opt.) vs {final} (baseline)', m_final, m_base)]:
        s, p = wilcoxon(a, b)
        main_rows.append({'Protocol': P, 'Comparison': comp,
                          'Mean MCC (first)': a.mean(), 'Mean MCC (second)': b.mean(),
                          'Folds first > second': int((a > b).sum()),
                          'W': s, 'p-value': p, 'Rank-biserial r': rank_biserial(a, b)})


df_main = pd.DataFrame(main_rows)
rej, ph, _, _ = multipletests(df_main['p-value'], alpha=0.05, method='holm')
df_main['p (Holm, 6 tests)'] = ph
df_main['Significant (Holm)'] = rej

df_main.to_csv(f'{OUT}/table_wilcoxon_main.csv', index=False)
print(df_main.round(4).to_string(index=False))


pd.DataFrame(fold_rows).to_csv(f'{OUT}/table_per_fold_mcc.csv', index=False)
print(f'Saved to {OUT}')